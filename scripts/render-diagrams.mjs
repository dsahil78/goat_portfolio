import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const sourceDir = path.join(root, 'content/diagrams');
const outputDir = path.join(root, 'public/diagrams');
await fs.mkdir(outputDir, { recursive: true });
const files = (await fs.readdir(sourceDir)).filter(file => file.endsWith('.mmd') && !file.endsWith('.mobile.mmd')).sort();
const browser = await chromium.launch({ headless: true });
const manifest = {};
const classes = '\nclassDef focus fill:#DBEAFE,stroke:#1D4ED8,stroke-width:1.5px,color:#1E3A8A;\nclassDef human fill:#FFFFFF,stroke:#7C2D3B,stroke-width:1.5px,color:#7C2D3B;';
try {
  const page = await browser.newPage({ viewport: { width: 1800, height: 1400 } });
  await page.setContent('<!doctype html><html><head></head><body></body></html>');
  await page.addScriptTag({ path: path.join(root, 'node_modules/mermaid/dist/mermaid.min.js') });
  for (const file of files) {
    const name = file.replace('.mmd', '');
    const original = await fs.readFile(path.join(sourceDir, file), 'utf8');
    manifest[name] = {};
    for (const variant of ['desktop', 'mobile']) {
      let source = original.replace(/^flowchart (LR|TB)/, `flowchart ${variant === 'mobile' || name.endsWith('-overview') ? 'TB' : 'LR'}`);
      if (variant === 'mobile') {
        try { source = await fs.readFile(path.join(sourceDir, `${name}.mobile.mmd`), 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
        source = source.replace('Tally · Zoho · Vyapar<br/>Customer systems', 'Existing ERPs +<br/>customer systems')
          .replace('Supply · subject · price<br/>Geography · session intent', 'Supply · subject · price<br/>Geography · intent')
          .replace('Feedback · support · CRM<br/>Reviews · backlog', 'Customer signals<br/>and backlog')
          .replace('Inventory +<br/>replenishment', 'Inventory<br/>decisions')
          .replace('Stale data /<br/>exceptions', 'Visible<br/>exceptions');
      }
      const result = await page.evaluate(async ({ name, variant, source }) => {
        window.mermaid.initialize({
          startOnLoad: false, securityLevel: 'strict', theme: 'base', htmlLabels: false,
          deterministicIds: true, deterministicIDSeed: `${name}-${variant}`,
          fontFamily: 'Arial, sans-serif',
          themeVariables: {
            fontFamily: 'Arial, sans-serif', fontSize: '17px', primaryColor: '#FFFFFF',
            primaryTextColor: '#111827', primaryBorderColor: '#A9B6CB',
            lineColor: '#718096', secondaryColor: '#EEF4FF', tertiaryColor: '#F4F6FA',
            edgeLabelBackground: '#FAFAF7', clusterBkg: '#F4F6FA', clusterBorder: '#E5E7EB',
          },
          flowchart: { htmlLabels: false, curve: 'linear', nodeSpacing: 30, rankSpacing: name.endsWith('-overview') ? 22 : variant === 'mobile' ? 32 : 42, padding: 16, useMaxWidth: false },
        });
        const { svg } = await window.mermaid.render(`diagram-${name}-${variant}`, source);
        const document = new DOMParser().parseFromString(svg, 'image/svg+xml');
        const element = document.documentElement;
        if (document.querySelector('parsererror')) throw new Error('Invalid SVG');
        const [, , width, height] = element.getAttribute('viewBox').split(/\s+/).map(Number);
        element.setAttribute('width', String(Math.ceil(width)));
        element.setAttribute('height', String(Math.ceil(height)));
        element.removeAttribute('style');
        for (const rect of element.querySelectorAll('.node rect')) { rect.setAttribute('rx', '10'); rect.setAttribute('ry', '10'); }
        if (element.querySelector('script, foreignObject')) throw new Error('Unexpected SVG content: '+element.querySelector('script, foreignObject').outerHTML.slice(0,300));
        return { svg: new XMLSerializer().serializeToString(element), width: Math.ceil(width), height: Math.ceil(height) };
      }, { name, variant, source: source + classes });
      const filename = `${name}-${variant}.svg`;
      await fs.writeFile(path.join(outputDir, filename), result.svg);
      manifest[name][variant] = { src: `/diagrams/${filename}`, width: result.width, height: result.height };
      console.log(`${filename}: ${result.width} × ${result.height}`);
    }
  }
  await fs.writeFile(path.join(root, 'content/diagram-assets.ts'), `// Generated by npm run diagrams:build. Do not edit by hand.\nexport const diagramAssets = ${JSON.stringify(manifest, null, 2)} as const;\n`);
} finally {
  await browser.close();
}
